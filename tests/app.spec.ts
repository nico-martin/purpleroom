import { expect, test } from "@playwright/test";

test("the crew can take a conference from shortlist to stage", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/setup");
  await page.getByLabel("Setup key", { exact: true }).fill("green-room-browser-test-key-not-for-production");
  await page.getByLabel("Your name", { exact: true }).fill("Nico");
  await page.getByLabel("Email address", { exact: true }).fill("ui-test@example.com");
  await page.getByRole("button", { name: "Create my account", exact: true }).click();
  await expect(page.getByRole("heading", { name: /Nico\./ })).toBeVisible();
  await page.getByRole("button", { name: "Sign out", exact: true }).click();
  await page.goto("/talks");
  await expect(page.getByRole("heading", { name: "Welcome to the room." })).toBeVisible();
  await page.getByLabel("Email address").fill("ui-test@example.com");
  await page.getByRole("button", { name: "Send me a sign-in link" }).click();
  await expect(page.getByText("Check your inbox.")).toBeVisible();
  const link = await page.getByRole("link", { name: "Open your sign-in link" }).getAttribute("href");
  await page.goto(new URL(link!).pathname);
  await expect(page.getByRole("heading", { name: "Ideas looking for a stage." })).toBeVisible();
  await page.getByRole("button", { name: "New talk", exact: true }).click();
  await page.getByLabel("Talk title", { exact: true }).fill("The web is for everyone");
  await page.getByLabel("Abstract", { exact: true }).fill("A deeply private abstract about accessible interfaces.");
  await page.getByRole("button", { name: "Add to my library" }).click();
  await expect(page.getByRole("link", { name: "The web is for everyone" })).toBeVisible();
  await page.getByRole("link", { name: "Conferences", exact: true }).click();
  await page.getByRole("link", { name: "Add a conference", exact: true }).first().click();
  await page.getByLabel("Conference name").fill("JSNation");
  await page.getByLabel("Conference website").fill("https://jsnation.com");
  await page.getByLabel("A little context").fill("A gathering of JavaScript people with good questions and better conversations.");
  await page.getByRole("button", { name: "Add conference", exact: true }).click();
  await expect(page.getByRole("heading", { name: "JSNation", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Write a speaker take" }).click();
  await page.getByRole("button", { name: "Covers travel", exact: true }).click();
  await page.getByRole("button", { name: "Great speaker care", exact: true }).click();
  await page.getByLabel("Your speaker take").fill("Smooth from CFP to stage. Flights and hotel booked for you, and the recording was online two weeks later.");
  await page.getByRole("button", { name: "Yes, gladly" }).click();
  await page.getByRole("button", { name: "Save my take" }).click();
  await expect(page.getByText("Would return", { exact: true })).toBeVisible();
  await page.getByRole("link", { name: "New edition" }).click();
  const future = (days: number) => new Date(Date.now() + days * 86400000).toISOString().slice(0, 10);
  await page.getByLabel("Year", { exact: true }).fill(String(new Date(future(90)).getFullYear()));
  await page.getByLabel("City", { exact: true }).fill("Amsterdam");
  await page.getByLabel("Country code").fill("NL");
  await page.getByLabel("First day").fill(future(90));
  await page.getByLabel("Last day").fill(future(91));
  await page.getByLabel("CFP closes").fill(future(5));
  await page.getByRole("button", { name: "Add edition", exact: true }).click();
  await expect(page.getByRole("heading", { name: /JSNation \d{4}/ })).toBeVisible();
  await page.getByRole("button", { name: "Add my talk", exact: true }).click();
  await page.getByLabel("Submission status").selectOption("confirmed");
  await page.getByRole("button", { name: "Add my talk", exact: true }).last().click();
  await expect(page.locator("span").filter({ hasText: /^Confirmed$/ })).toBeVisible();
  await page.getByRole("button", { name: "Going", exact: true }).click();
  await expect(page.getByRole("button", { name: "Going", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.getByRole("textbox", { name: "Your comment" }).fill("See you there. Speaker dinner, anyone?");
  await page.getByRole("button", { name: "Leave a note" }).click();
  await expect(page.getByText("See you there. Speaker dinner, anyone?")).toBeVisible();
  await page.getByRole("link", { name: "The room", exact: true }).click();
  await expect(page.getByRole("heading", { name: /Nico\./ })).toBeVisible();
  await expect(page.getByText("5 days", { exact: true })).toBeVisible();
  await expect(page.getByText("1 speaking", { exact: true })).toBeVisible();
  await page.screenshot({ path: "test-results/dashboard-desktop.png", fullPage: true, animations: "disabled" });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole("button", { name: "Open navigation" })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: "test-results/dashboard-mobile.png", fullPage: true, animations: "disabled" });
  await page.getByRole("button", { name: "Open navigation" }).click();
  await page.getByRole("link", { name: "Settings", exact: true }).click();
  await page.getByLabel("Your name", { exact: true }).fill("Nico Speaker");
  await page.getByRole("button", { name: "Save profile" }).click();
  await expect(page.getByText("Looking good. Your profile is saved.")).toBeVisible();
  await page.getByRole("group", { name: "Colour theme" }).getByRole("button", { name: "Dark", exact: true }).click();
  await expect(page.locator("html")).toHaveAttribute("data-theme", "dark");
  await page.reload();
  await expect(page.getByRole("group", { name: "Colour theme" }).getByRole("button", { name: "Dark", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.getByRole("group", { name: "Colour theme" }).getByRole("button", { name: "System", exact: true }).click();
  await page.emulateMedia({ colorScheme: "dark" });
  await page.screenshot({ path: "test-results/settings-dark-mobile.png", fullPage: true, animations: "disabled" });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.goto("/crew");
  await page.getByRole("button", { name: "Invite a friend", exact: true }).click();
  await page.getByRole("button", { name: "Create invite link" }).click();
  await expect(page.getByLabel("invite link", { exact: true })).toHaveValue(/\/invite\/[a-f0-9]{64}$/);
  await page.getByRole("button", { name: "Done", exact: true }).click();
  await expect(page.getByText("An open seat at the table")).toBeVisible();
  await page.goto("/talks");
  await page.getByRole("link", { name: "The web is for everyone", exact: true }).click();
  await expect(page.getByText("A deeply private abstract about accessible interfaces.")).toBeVisible();
  await page.getByRole("button", { name: "Edit talk", exact: true }).click();
  await page.getByLabel("Private notes").fill("Remember to bring the accessible demos.");
  await page.getByRole("button", { name: "Save changes", exact: true }).click();
  await expect(page.getByText("Remember to bring the accessible demos.")).toBeVisible();
  await page.getByRole("link", { name: /JSNation \d{4}/ }).click();
  await expect(page.getByRole("heading", { name: "Call for papers", exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  page.on("dialog", (dialog) => dialog.accept());
  await page.getByRole("button", { name: "Move to recently deleted", exact: true }).click();
  await expect(page.getByRole("heading", { name: "JSNation", exact: true })).toBeVisible();
  await page.goto("/trash");
  await page.getByRole("button", { name: "Restore", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Nothing left behind." })).toBeVisible();
  expect(errors).toEqual([]);
});
